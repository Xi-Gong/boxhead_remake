/**
 * Generates src/game/packages.ts and src/game/allClasses.ts from the list of AS2 classes in assets/projects/boxhead4.
 *
 *   node tools/gen-packages.ts
 *
 * Why: AS2 resolves classes at runtime through `_global` package objects (`World.CWorld`, `Thing.Creature.X`), so the
 * original code has no load-order cycles. The TS port mirrors that: every game class module imports ONLY its base class
 * (for `extends`) plus these package objects, and registers itself at the end of its module with
 * `registerGameClass('<dotted.path>', Class)`. Cross-class references keep the exact AS2 dotted spelling and are typed
 * through `typeof import(...)` (type-only, erased at runtime → no ES module cycles).
 */
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { AS2_DIR, ROOT } from './paths.ts';

// v0.2.0: assets/projects was deleted from the repo (regenerable from the SWF via ffdec - see assets/README.md).
// The generated outputs (src/game/packages.ts, src/game/allClasses.ts) are committed, so this tool is only needed
// when a NEW class is ported.
if (!existsSync(AS2_DIR)) {
  console.error(`gen-packages: ${AS2_DIR} not found. The decompiled AS2 sources were removed from the repo in ` +
    `v0.2.0; regenerate them with ffdec (see assets/README.md, "Regenerating the deleted reference material").`);
  process.exit(1);
}

function listAs(dir: string): string[] {
  const out: string[] = [];
  for (const f of readdirSync(dir).sort()) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) out.push(...listAs(p));
    else if (f.endsWith('.as')) out.push(relative(AS2_DIR, p).replace(/\\/g, '/').replace(/\.as$/, ''));
  }
  return out;
}

const classes = listAs(AS2_DIR); // e.g. "Thing/Creature/CThing_Creature_Player", "CMain"
const topLevel = classes.filter((c) => !c.includes('/'));
const packaged = classes.filter((c) => c.includes('/'));

interface Node { children: Map<string, Node>; classes: string[] }
const newNode = (): Node => ({ children: new Map(), classes: [] });
const tree = new Map<string, Node>();
for (const c of packaged) {
  const parts = c.split('/');
  const cls = parts.pop()!;
  let level = tree;
  let node: Node | undefined;
  for (const p of parts) {
    if (!level.has(p)) level.set(p, newNode());
    node = level.get(p)!;
    level = node.children;
  }
  node!.classes.push(cls);
}

const typeName = (path: string) => 'T_' + path.replace(/\//g, '_');
const indent = (n: number) => '  '.repeat(n);

function typeOf(node: Node, path: string[], depth: number): string {
  const lines: string[] = ['{'];
  for (const [k, child] of node.children) lines.push(`${indent(depth + 1)}${k}: ${typeOf(child, [...path, k], depth + 1)};`);
  for (const cls of node.classes) lines.push(`${indent(depth + 1)}${cls}: ${typeName([...path, cls].join('/'))};`);
  lines.push(`${indent(depth)}}`);
  return lines.join('\n');
}

function valueOf(node: Node, depth: number): string {
  if (!node.children.size) return '{}';
  const lines: string[] = ['{'];
  for (const [k, child] of node.children) lines.push(`${indent(depth + 1)}${k}: ${valueOf(child, depth + 1)},`);
  lines.push(`${indent(depth)}}`);
  return lines.join('\n');
}

const out: string[] = [];
out.push('/* GENERATED by tools/gen-packages.ts — do not edit by hand. */');
out.push('/* eslint-disable */');
out.push('/**');
out.push(' * AS2 package namespaces for the game port (the TS equivalent of `_global.World`, `_global.Thing`, ...).');
out.push(' *');
out.push(' * Usage in a ported class module:');
out.push(" *   import { CMain, CSound, Thing, World } from '../packages.ts';   // runtime-resolved, never cyclic");
out.push(" *   import { CThing } from '../Thing/CThing.ts';                     // ONLY for `extends` (base class)");
out.push(' *   ... World.Map.CMap_Cell.mCollide_Solid ...   CMain.mFPS ...      // exact AS2 spelling');
out.push(" *   registerGameClass('Thing.Creature.CThing_Creature_Player', CThing_Creature_Player); // last line of the module");
out.push(' *');
out.push(' * Package members are only valid after src/game/allClasses.ts has been imported (all modules registered), i.e. at');
out.push(' * runtime inside methods — never in static initializers evaluated at module load.');
out.push(' */');
out.push('');
for (const c of classes) {
  const cls = c.split('/').pop()!;
  out.push(`type ${typeName(c)} = typeof import('./${c}.ts').${cls};`);
}
out.push('');
for (const [k, node] of tree) {
  out.push(`export const ${k} = ${valueOf(node, 0)} as unknown as ${typeOf(node, [k], 0)};`);
  out.push('');
}
for (const c of topLevel) out.push(`export let ${c}: ${typeName(c)} = undefined as unknown as ${typeName(c)};`);
out.push('');
out.push('const packages: Record<string, any> = { ' + [...tree.keys()].map((k) => `${k}`).join(', ') + ' };');
out.push('');
out.push('/** Register a ported class under its AS2 dotted path (e.g. "World.Map.CMap_Cell" or "CMain"). */');
out.push('export function registerGameClass(path: string, cls: unknown): void {');
out.push("  const parts = path.split('.');");
out.push('  if (parts.length === 1) {');
out.push('    switch (parts[0]) {');
for (const c of topLevel) out.push(`      case '${c}': ${c} = cls as ${typeName(c)}; return;`);
out.push("      default: throw new Error(`registerGameClass: unknown top-level class ${path}`);");
out.push('    }');
out.push('  }');
out.push('  let node: any = packages[parts[0]];');
out.push("  if (!node) throw new Error(`registerGameClass: unknown package ${path}`);");
out.push('  for (let i = 1; i < parts.length - 1; i++) {');
out.push('    node = node[parts[i]];');
out.push("    if (!node) throw new Error(`registerGameClass: unknown package ${path}`);");
out.push('  }');
out.push('  node[parts[parts.length - 1]] = cls;');
out.push('}');
out.push('');
out.push('/** All AS2 class paths (dotted), for completeness checks. */');
out.push('export const ALL_CLASS_PATHS: readonly string[] = [');
for (const c of classes) out.push(`  '${c.replace(/\//g, '.')}',`);
out.push('];');
out.push('');

const gameDir = resolve(ROOT, 'src', 'game');
writeFileSync(join(gameDir, 'packages.ts'), out.join('\n'));

const all: string[] = [];
all.push('/* GENERATED by tools/gen-packages.ts — do not edit by hand. */');
all.push('/** Side-effect imports of every ported class module (each registers itself via registerGameClass). */');
for (const c of classes) all.push(`import './${c}.ts';`);
all.push('');
writeFileSync(join(gameDir, 'allClasses.ts'), all.join('\n'));

console.log(`gen-packages: ${classes.length} classes (${topLevel.length} top-level, packages: ${[...tree.keys()].join(', ')})`);
