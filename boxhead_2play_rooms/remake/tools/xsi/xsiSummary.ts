/**
 * Builds generated/reports/xsi-summary.md: the XSI data model as found in sprite 755's DoAction, with the facts the
 * XSI renderer port (projects/boxhead4/DrawPrimitive/XSI/*.as) needs. All tables are computed from the evaluated data;
 * the prose explains how CDrawPrimitive_XSI_DI / _Animation / _StyleSheet / _Collection consume each field.
 *
 *   node tools/xsi/xsiSummary.ts      (or: node tools/xsi/extractXsi.ts, which also writes it)
 */
