class Range {
  min = Infinity;
  max = -Infinity;
  n = 0;
  add(v: number): void { this.n++; if (v < this.min) this.min = v; if (v > this.max) this.max = v; }
  toString(): string { return this.n ? `${fmt(this.min)} .. ${fmt(this.max)} (n=${this.n})` : '-'; }
}
const fmt = (v: number) => (Number.isInteger(v) ? String(v) : v.toFixed(4).replace(/0+$/, ''));
const inc = <K>(m: Map<K, number>, k: K, by = 1) => m.set(k, (m.get(k) ?? 0) + by);
const nums = (v: AsValue | undefined) => asArray(v).map((x) => x as number);
const SIN45 = Math.SQRT1_2;

/** Camera "nearness" of a model anchor (bigger = closer to the viewer): camera is south (-mY) and above (-mZ). */
function nearness(model: AsValue): number | undefined {
  const vp = asGet(asGet(model, 'XSIInfo'), 'vPosition');
  const y = asGet(vp, 'mY'), z = asGet(vp, 'mZ');
  return typeof y === 'number' && typeof z === 'number' ? (-y - z) * SIN45 : undefined;
}

export function buildXsiSummary(ev: XsiEvaluation): string {
  const items = ev.items;
  const views = items.map((it, i) => itemView(it, i));
  const stats = computeXsiStats(items);
  const byId = new Map(views.map((v) => [v.id, v]));
  const L: string[] = [];
  const p = (s = '') => L.push(s);

  // local variable name of each item's mXSI object (identity lookup in the VM timeline)
  const varName = new Map<unknown, string>();
  for (const [k, val] of ev.vm.timeline.props) varName.set(val, k);
  const itemVar = ev.vmItems.map((o) => varName.get(o.get('mXSI')) ?? '?');

  p('# XSI character data (sprite 755) — data model as found');
  p();
  p('Generated by `node tools/xsi/extractXsi.ts` (lane B2) from `../boxhead_2play_rooms.swf`. Output: `public/assets/xsi.json`');
  p('(`XsiJson` in `src/shared/assetSchema.ts`: objects are `{ $: [[name, value], ...] }` in creation order, arrays plain).');
  p();
  p('## 1. Source script');
  p();
  p(`- Export \`${XSI_EXPORT_NAME}\` → DefineSprite **${ev.script.spriteId}**, one DoAction of **${ev.script.length.toLocaleString('en-US')} bytes** at decompressed offset ${ev.script.offset}.`);
  p(`- Executed by \`tools/avm1/dataVm.ts\`: ${ev.vm.actions.toLocaleString('en-US')} actions, no warnings. Opcode counts: ` +
    Object.entries(ev.vm.opcodeCounts).map(([k, v]) => `${k} ${v}`).join(', ') + '.');
  p(`- trace output: ${ev.vm.traces.map((t) => `\`${t}\``).join(', ')}. Timeline variables at the end: ${ev.vm.timeline.props.size} (` +
    `\`mRotations\`, \`mXSIInfo\`, \`mMaterials\` hold the last item's values; \`mItems\`; \`mLoaded = ${String(ev.vm.timeline.get('mLoaded'))}\`; 40 × \`m<Group>_Default_<Anim>\`).`);
  p(`- Objects referenced from more than one place: ${ev.sharedRefs} (every item owns its own objects; the JSON loses no sharing).`);
  p();
  p('Script shape (AS2 equivalent; 4 `var`s per item, then the item list):');
  p();
  p('```actionscript');
  p('var mRotations = [ [ {Models: {Head: {...}, ...}}, ... ], ... ];   // [direction][frame]');
  p('var mXSIInfo   = {mTilt: 45, mLight: {mX: 0.176.., mY: 0.440.., mZ: -0.880..}};');
  p('var mMaterials = {Shadow: {...}, Edge: {...}, PEdge: {...}, <name>: {...}, ...};');
  p('var mDevil_Default_Dead = {mRotations: mRotations, mMaterials: mMaterials, mXSIInfo: mXSIInfo};');
  p('// ... 40 times ...');
  p('mItems = new Array();');
  p('_global.mXSI_Data = {mItems: mItems};');
  p('mItems.push({mGroupID: "Player", mAnimID: "Stand", mXSI: mPlayer_Default_Stand});');
  p('mItems.push({mGroupID: "Player", mAnimID: "Walk", mXSI: mPlayer_Default_Walk, mFrameSquence: [0,1,2,3,4,3,2,1]});');
  p('mItems.push({mGroupID: "Player_Alternate1", mAnimID: "Stand", mXSI: ..., mRenderPartner: "Player"});');
  p('// ... 40 pushes ...');
  p('trace("IMPORTED XSI DATA! No. Items = " + _global.mXSI_Data.mItems.length);');
  p('mLoaded = true;');
  p('```');
  p();
  p('Consumer: `CMain.as:57` → `new CDrawPrimitive_XSI_DI(_global.mXSI_Data.mItems)`, then `delete _global.mXSI_Data`.');
  p();

  // ------------------------------------------------------------------ totals
  p('## 2. Totals (verified; asserted in tests/unit/avm1/xsi.test.ts)');
  p();
  p(`| items | direction-frames | polygons | vertices |`);
  p(`|---|---|---|---|`);
  p(`| ${stats.items} | ${stats.directionFrames} | ${stats.polygons.toLocaleString('en-US')} | ${stats.vertices.toLocaleString('en-US')} |`);
  p();
  p('Definitions: *direction-frames* = Σ over items and directions of `mRotations[d].length`; *polygons* = number of');
  p('`Shape_vList` entries of all non-Empty models (Shadow and PEdge polygons excluded); *vertices* = Σ `vList.length / 2`');
  p('over those polygons (vertices written twice to close a polygon are counted as written).');
  p();

  // ------------------------------------------------------------------ items
  p('## 3. Items (`mItems` order)');
  p();
  p('| # | mGroupID | mAnimID | mRenderPartner | mFrameSquence | dirs × frames | polys | verts | mats | local var |');
  p('|---|---|---|---|---|---|---|---|---|---|');
  views.forEach((v, i) => {
    const frames = [...new Set(v.rotations.map((d) => d.length))].join('/');
    const s = computeXsiStats([items[i]]);
    const nm = asKeys(asGet(v.xsi, 'mMaterials')).length;
    p(`| ${i} | ${v.groupID} | ${v.animID} | ${v.renderPartner ?? ''} | ${v.frameSequence ? `[${v.frameSequence.join(',')}]` : ''} | ` +
      `${v.rotations.length} × ${frames} | ${s.polygons} | ${s.vertices} | ${nm} | \`${itemVar[i]}\` |`);
  });
  p();
  const groups = new Map<string, XsiItemView[]>();
  for (const v of views) groups.set(v.groupID, [...(groups.get(v.groupID) ?? []), v]);
  p('Groups: ' + [...groups].map(([g, vs]) => `**${g}** ${vs.length}`).join(', ') + '.');
  p();
  const shapes = new Map<string, Set<string>>();
  for (const v of views) {
    const k = `${v.animID}`;
    const sh = `${v.rotations.length}×${[...new Set(v.rotations.map((d) => d.length))].join('/')}` +
      (v.frameSequence ? ` seq [${v.frameSequence.join(',')}]` : '');
    shapes.set(k, (shapes.get(k) ?? new Set()).add(`${sh} (${v.groupID})`));
  }
  p('Animation shapes (directions × frames per direction):');
  p();
  for (const [anim, set] of shapes) p(`- **${anim}**: ${[...set].join('; ')}`);
  p();
  p('Every direction of an item has the same frame count. Directions: 16 for Stand sets, 8 for Walk/Hit/Attack,');
  p('4 for Dying/Dead. Direction 0 faces east (+x) and directions advance clockwise on screen (y down): of 16, dir 4');
  p('shows `Body_Front`/`Head_Front` (faces the viewer, south) and dir 12 shows `Body_Back`/`Head_Back`.');
  p('The runtime picks a direction with `CThing_Angle.mLookup256[nDirections][angle256]` (`Init_AnimationObject`).');
  p();
  // Player_Zombie_Walk anomaly
  const pzw = byId.get('Player_Zombie_Walk');
  if (pzw) {
    const fr = (d: number, f: number) => JSON.stringify(pzw.rotations[d][f]);
    const same = [5, 6, 7].map((f) => [f, 8 - f]).map(([a, b]) => pzw.rotations.every((_, d) => fr(d, a) === fr(d, b)));
    p(`**Anomaly:** \`Player_Zombie_Walk\` has ${pzw.rotations.length} × ${pzw.rotations[0].length} frames although its`);
    p(`\`mFrameSquence\` is [${pzw.frameSequence?.join(',')}]: frames 5..7 are never referenced (compared with frames 3, 2, 1 in`);
    p(`every direction they are ${same.map((x) => (x ? 'identical' : 'different')).join(' / ')}).`);
    p('It is only used as the render partner of `Zombie_Zombie_Walk` (8 × 5), which reads partner frames 0..4.');
    p();
  }

  // ------------------------------------------------------------------ data model
  p('## 4. Data model (key names and shapes)');
  p();
  p('Property lists below are in **stored `$` order** (creation order as executed = InitObject pop order = reverse of the');
  p('order in which the exporter wrote them).');
  p();
  const itemKeyOrders = new Map<string, number>();
  const xsiKeyOrders = new Map<string, number>();
  const frameKeyOrders = new Map<string, number>();
  const modelKeyOrders = new Map<string, number>();
  const xsiInfoKeys = new Map<string, number>();
  const vposKeys = new Map<string, number>();
  const matrixKeys = new Map<string, number>();
  for (const v of views) {
    inc(itemKeyOrders, asKeys(items[v.index]).join(', '));
    inc(xsiKeyOrders, asKeys(v.xsi).join(', '));
    for (const d of v.rotations) for (const f of d) {
      inc(frameKeyOrders, asKeys(f).join(', '));
      for (const [, m] of frameModels(f).$) {
        inc(modelKeyOrders, asKeys(m).join(', ') + (isEmptyModel(m) ? '  (Empty: true)' : ''));
        const xi = asGet(m, 'XSIInfo');
        if (xi !== undefined) { inc(xsiInfoKeys, asKeys(xi).join(', ')); inc(vposKeys, asKeys(asGet(xi, 'vPosition')).join(', ')); }
        for (const mx of asArray(asGet(m, 'Shape_Matrix'))) if (isAsObject(mx)) inc(matrixKeys, asKeys(mx).join(', '));
      }
    }
  }
  const listCounts = (m: Map<string, number>) => [...m].map(([k, n]) => `\`{${k}}\` ×${n}`).join('; ');
  p('```text');
  p('mItems: Array<Item>');
  p('Item   = { mGroupID: string, mAnimID: string, mXSI: XSI, mFrameSquence?: number[], mRenderPartner?: string }');
  p('XSI    = { mRotations: Frame[][] /* [direction][frame] */, mMaterials: {[name]: Material}, mXSIInfo: {mTilt, mLight} }');
  p('Frame  = { Models: {[modelName]: Model} }');
  p('Model  = { Empty: true }                                      // placeholder -> render partner\'s model');
  p('       | { Empty: false, Shape_vList: number[][], Shape_Material: string[], Shape_Matrix: (0 | Mat)[],');
  p('           Shape_Brightness: number[], Shadow: number[][], PEdge: number[][], Edge: [], XSIInfo: {vPosition: {mX,mY,mZ}} }');
  p('Mat    = { a, b, c, d, tx, ty }                                // plain object (not flash.geom.Matrix)');
  p('Material = { mColor, mAlpha } | { mcLinkID: "<Name>_MC", mSize: {x: 64, y: 64} } | PEdge/Edge { mThickness, mColor, mAlpha }');
  p('```');
  p();
  p(`- Item key orders: ${listCounts(itemKeyOrders)}`);
  p(`- XSI key orders: ${listCounts(xsiKeyOrders)}`);
  p(`- Frame key orders: ${listCounts(frameKeyOrders)}`);
  p(`- Model key orders: ${listCounts(modelKeyOrders)}`);
  p(`- XSIInfo keys: ${listCounts(xsiInfoKeys)}; vPosition keys: ${listCounts(vposKeys)}`);
  p(`- Shape_Matrix object keys: ${listCounts(matrixKeys)}`);
  p();

  // model names per group
  p('### Model names per group');
  p();
  p('| group | model names (union) | non-Empty models (count of direction-frames) |');
  p('|---|---|---|');
  for (const [g, vs] of groups) {
    const all = new Set<string>();
    const real = new Map<string, number>();
    for (const v of vs) for (const d of v.rotations) for (const f of d) {
      for (const [mn, m] of frameModels(f).$) { all.add(mn); if (!isEmptyModel(m)) inc(real, mn); }
    }
    p(`| ${g} | ${[...all].join(', ')} | ${[...real].map(([k, n]) => `${k} (${n})`).join(', ')} |`);
  }
  p();
  // model set constancy per item
  let constSets = 0, varyingOrder = 0;
  const varying: string[] = [];
  for (const v of views) {
    const sets = new Map<string, string[]>(), orders = new Set<string>();
    v.rotations.forEach((d, di) => d.forEach((f, fi) => {
      const k = asKeys(frameModels(f));
      const key = [...k].sort().join(',');
      sets.set(key, [...(sets.get(key) ?? []), `d${di}f${fi}`]);
      orders.add(k.join(','));
    }));
    if (sets.size === 1) constSets++;
    else {
      const all = new Set([...sets.keys()].flatMap((k) => k.split(',')));
      const partial = [...all].filter((n) => [...sets.keys()].some((k) => !k.split(',').includes(n)));
      const desc = partial.map((n) => {
        const present = [...sets].filter(([k]) => k.split(',').includes(n)).flatMap(([, w]) => w);
        const absent = [...sets].filter(([k]) => !k.split(',').includes(n)).flatMap(([, w]) => w);
        return present.length <= absent.length ? `${n} present only in ${present.join(' ')}` : `${n} absent in ${absent.join(' ')}`;
      });
      varying.push(`\`${v.id}\` (${desc.join('; ')})`);
    }
    if (orders.size > 1) varyingOrder++;
  }
  p(`Within an item every direction-frame has the same set of model names in ${constSets}/${views.length} items; exceptions:`);
  p(`${varying.join('; ')} — an Empty placeholder that the style sheets hide anyway. The **order** of the models`);
  p(`changes with direction/frame in ${varyingOrder}/${views.length} items (it is a depth order, see §6).`);
  p();
  const hw = byId.get('Player_Handgun_Walk');
  if (hw) {
    const m0 = frameModels(hw.rotations[0][0]);
    // names written by CDrawPrimitive_XSI_StyleSheet.as (SS_BAMBO/BOND/GIJOE/SWAT/ZOMBIE/DEVIL)
    const ssModels = ['GunPosition_Right', 'Body_Front', 'Body_Back', 'Head', 'Foot_Right', 'Foot_Left', 'Weapon_Right'];
    const missing = ssModels.filter((n) => !asKeys(m0).includes(n));
    p('`GetStyleSheet("Player_Handgun_Walk")` copies the model names of `mDirections[0][0].Models` of that set: ' +
      asKeys(m0).map((k) => `${k}${isEmptyModel(asGet(m0, k)!) ? '' : '*'}`).join(', ') + ' (* = non-Empty).');
    p(`Model names written by the style sheets (${ssModels.join(', ')}) missing from that list: ${missing.length ? missing.join(', ') : 'none'}.`);
    p();
  }

  // ------------------------------------------------------------------ materials & xsi info
  p('## 5. Materials and mXSIInfo');
  p();
  const matDefs = new Map<string, Map<string, number>>();
  for (const v of views) {
    for (const [name, def] of asGet(v.xsi, 'mMaterials') ? (asGet(v.xsi, 'mMaterials') as { $: [string, AsValue][] }).$ : []) {
      const m = matDefs.get(name) ?? new Map<string, number>();
      inc(m, JSON.stringify(def));
      matDefs.set(name, m);
    }
  }
  const mainMats = asKeys(asGet(byId.get('Player_Stand')?.xsi, 'mMaterials'));
  p(`${matDefs.size} distinct material names over all items; every name has exactly one definition (identical in every item):`);
  p(`${[...matDefs.values()].every((m) => m.size === 1) ? 'yes' : '**NO**'}. The base Player sets have ${mainMats.length} materials`);
  p(`(${mainMats.join(', ')}). \`Register_Materials\` merges all of them into \`mMasterMaterials\`.`);
  // materials written by CDrawPrimitive_XSI_StyleSheet.as
  const ssMats = ['Body_Back', 'Body_Front', 'Body_Side', 'Body_Top', 'Head_Back', 'Head_Front', 'Head_Side', 'Bandana',
    'Cloth', 'LowerArm', 'UpperArm', 'Hand', 'Hair', 'Foot'];
  const missingMats = ssMats.filter((n) => !matDefs.has(n));
  p(`Materials written by the style sheets (${ssMats.join(', ')}) that do not exist: **${missingMats.join(', ') || 'none'}**`);
  p('→ `_loc1_.mMaterials.Cloth.mColor = …` (SS_BOND, SS_GIJOE, SS_SWAT) assigns to a member of `undefined`: a silent no-op');
  p('in AS2 (port with `?.`; there is no Cloth-coloured polygon).');
  p();
  p('| material | definition (stored order) | items | kind |');
  p('|---|---|---|---|');
  for (const [name, defs] of matDefs) {
    const [def, n] = [...defs][0];
    const parsed = JSON.parse(def) as AsValue;
    const kind = asGet(parsed, 'mcLinkID') !== undefined ? 'bitmap (attachMovie + BitmapData.draw)'
      : name === 'PEdge' || name === 'Edge' ? 'line style' : name === 'Shadow' ? 'shadow fill' : 'solid colour';
    const col = asGet(parsed, 'mColor');
    const desc = asKeys(parsed).map((k) => {
      const v = asGet(parsed, k);
      if (k === 'mColor' && typeof v === 'number') return `mColor 0x${v.toString(16).padStart(6, '0')}`;
      if (isAsObject(v)) return `${k} {${asKeys(v).map((kk) => `${kk}:${String(asGet(v, kk))}`).join(',')}}`;
      return `${k} ${String(v)}`;
    }).join(', ');
    void col;
    p(`| ${name} | ${desc} | ${n} | ${kind} |`);
  }
  p();
  const infos = new Map<string, number>();
  for (const v of views) inc(infos, JSON.stringify(asGet(v.xsi, 'mXSIInfo')));
  p(`mXSIInfo: ${infos.size} distinct value(s): ${[...infos].map(([k, n]) => `\`${k}\` ×${n}`).join('; ')}.`);
  p('→ `mTilt` 45 (degrees; DI converts to radians, `PFactor = -sin(tilt)`), `mLight` is a unit vector (stored, never used');
  p('by the renderer: lighting is pre-baked into `Shape_Brightness`).');
  p();

  // ------------------------------------------------------------------ paint order
  p('## 6. Paint order (for..in) evidence');
  p();
  p('`CDrawPrimitive_XSI_DI.Render` draws everything into ONE graphics plane, so later fills cover earlier ones; the order');
  p('is decided by AS2 `for..in` over `oFrame.Models` (an InitObject-built object) and over the per-model arrays');
  p('(`Shape_vList` etc., InitArray-built). The data lets us determine both orders without running Flash:');
  p();
  p('**Models — paint in stored `$` order (first entry first).** Each real model has `XSIInfo.vPosition`, a 3D anchor');
  p('(mX east, mY north, mZ = −height). Its screen projection is ≈ (mX, (mZ − mY)·sin45°) (checked against vertex');
  p('centroids below), so the distance towards the viewer (south and above) is `near = (−mY − mZ)·sin45°`.');
  p();
  const pw = byId.get('Player_Walk');
  if (pw) {
    const M = frameModels(pw.rotations[0][0]);
    p('Player_Walk, direction 0, frame 0 — model keys in stored `$` order:');
    p();
    p('| # | model | Empty | vPosition (mX, mY, mZ) | near | polys |');
    p('|---|---|---|---|---|---|');
    M.$.forEach(([mn, m], i) => {
      const vp = asGet(asGet(m, 'XSIInfo'), 'vPosition');
      const n = nearness(m);
      p(`| ${i} | ${mn} | ${String(asGet(m, 'Empty'))} | ${vp ? `${fmt(asGet(vp, 'mX') as number)}, ${fmt(asGet(vp, 'mY') as number)}, ${fmt(asGet(vp, 'mZ') as number)}` : ''} | ` +
        `${n === undefined ? '' : n.toFixed(1)} | ${asArray(asGet(m, 'Shape_vList')).length || ''} |`);
    });
    p();
  }
  // global pair statistics (with partner substitution for Empty models)
  let pairs = 0, ordered = 0, framesMono = 0, framesRev = 0, frames = 0;
  const centroidErr = new Range();
  for (const v of views) {
    const partner = v.renderPartner ? byId.get(`${v.renderPartner}_${v.animID}`) : undefined;
    v.rotations.forEach((dir, d) => dir.forEach((fr, f) => {
      frames++;
      const seq: number[] = [];
      for (const [mn, m0] of frameModels(fr).$) {
        let m: AsValue | undefined = m0;
        if (isEmptyModel(m0)) m = partner ? asGet(frameModels(partner.rotations[d][f]), mn) : undefined;
        if (m === undefined || isEmptyModel(m)) continue;
        const n = nearness(m);
        if (n === undefined) continue;
        seq.push(n);
        // projection check
        const vp = asGet(asGet(m, 'XSIInfo'), 'vPosition');
        let sy = 0, c = 0;
        for (const poly of asArray(asGet(m, 'Shape_vList'))) { const a = nums(poly); for (let k = 1; k < a.length; k += 2) { sy += a[k]; c++; } }
        if (c) centroidErr.add(Math.abs(sy / c - ((asGet(vp, 'mZ') as number) - (asGet(vp, 'mY') as number)) * SIN45));
      }
      let mono = true, rev = true;
      for (let i = 0; i < seq.length; i++) for (let j = i + 1; j < seq.length; j++) { pairs++; if (seq[j] >= seq[i]) ordered++; }
      for (let i = 1; i < seq.length; i++) { if (seq[i] < seq[i - 1]) mono = false; if (seq[i] > seq[i - 1]) rev = false; }
      if (mono) framesMono++;
      if (rev && seq.length > 1) framesRev++;
    }));
  }
  p(`Over all ${frames} direction-frames (Empty slots replaced by the render partner's model): **${ordered.toLocaleString('en-US')} of`);
  p(`${pairs.toLocaleString('en-US')} model pairs (${(100 * ordered / pairs).toFixed(1)}%) appear back-to-front** in stored order;`);
  p(`${framesMono} frames are perfectly sorted, ${framesRev} are sorted front-to-back. The remaining inversions involve large`);
  p('parts (mostly `Body`), whose anchor is a poor depth proxy. |vertex-centroid y − (mZ − mY)·sin45°| = ' + centroidErr.toString() + ' px.');
  p('Rendering a few frames (scratch rasterizer) confirms it: stored order puts the head over the body and the far');
  p('arm/foot behind; the reverse order paints feet and arms over the body.');
  p();
  p('**Polygons inside a model — paint from the LAST index to the FIRST** (`Shape_vList[n-1]` first). Overlaps inside');
  p('a model are rare (about 1,470 overlapping polygon pairs in 4,584 model instances, scratch convex-clipping');
  p('analysis: caps, hair/bandana, Devil face, weapons), but decisive: with descending order the `Player_Alternate1` cap brim (Bandana material) covers the face whenever the');
  p('head looks towards the viewer (Stand dirs 2, 4, 6) and disappears behind the cap when it looks away (dirs 10, 12, 14);');
  p('ascending order draws the brim behind the face in the first case and on top of the cap crown in the second.');
  p('So the exporter wrote everything nearest-first, and the game paints back-to-front by enumerating:');
  p();
  p('- InitObject-built objects (Models) in **stored `$` order** (= InitObject pop order = reverse of the written order);');
  p('- InitArray-built arrays in **descending index order**.');
  p();
  p('Both are what Flash Player\'s for..in must produce for these objects (if it enumerates newest-property-first, its');
  p('InitObject creates properties in push order; if oldest-first, arrays are special). Which internal rule Flash uses is');
  p('probe P1\'s job; **the XSI renderer port should not depend on a generic `forIn()` emulation: iterate Models `$` in');
  p('stored order and the polygon arrays from the last index down.** (Shadow polygons are all one colour under one filter');
  p('and PEdge strokes are all black, so their order is invisible.)');
  p();

  // ------------------------------------------------------------------ consumption
  p('## 7. How the AS2 renderer consumes each field');
  p();
  p('`CDrawPrimitive_XSI_DI` constructor (for..in over `mItems`): per item builds `{mGroupID, mAnimID, mID = group_anim,');
  p('mDirections = mXSI.mRotations, mTilt = mXSIInfo.mTilt·π/180, mLight, mFrameSequence = mFrameSquence}` and registers it');
  p('in `mGroups[mGroupID][mAnimID]` and `mAnimationSets[mID]`; `Register_Materials` merges `mXSI.mMaterials` into');
  p('`mMasterMaterials`; `CompileXSIData` stamps every frame object with `mDirection`, `mFrameIndex` (Number of the for..in');
  p('keys), `mAnimID` and `rPartner = mRenderPartner`. `LoadMaterials` attaches `mcLinkID` clips and draws them into a');
  p('`mSize.x × mSize.y` (64×64) transparent BitmapData `sBMD`.');
  p();
  p('`LoadAnimation(link, id)` (via `CDrawPrimitive_XSI_Animation.Load`): `Init_AnimationObject(mDirections.length)`,');
  p('`XSI_Info.Tilt/Light/PFactor = -sin(tilt)` (also sets `CThing_Position.mPFactor`); frame count = `mFrameSequence.length`');
  p('or the direction\'s frame count; for each direction and sequence slot it reuses the already queued frame when');
  p('`mFrameSequence[slot] != 0` and that frame exists, else queues a render (`AddToRenderStack`) of');
  p('`mDirections[d][slot]` — NOTE the decompiled loop reads `_loc3_[0]`/`mFrameSequence[0]` (counter artifact; resolve from');
  p('bytecode, plan appendix F). `FillXSIInfo` copies `Models[Hand_Right|Hand_Left|GunPosition_Right].XSIInfo.vPosition`');
  p('into `XSI_Info.XSI_Model_<name>` (`vPosition ×= mGlobalScale`, `nPosition = (x, PFactor·y, −z)/cellSize`).');
  p();
  p('`Render(oFrame)` (one direction-frame; mRenderFlags = Shadow|ProfileEdge|Texture|Shader):');
  p();
  p('1. `mGlobalScale = styleSheet.mScale` (0.35, Devil 0.44); clear `mcShadow` and the plane.');
  p('2. for each model of `oFrame.Models` (paint order §6): if `Empty` → use `mGroups[oFrame.rPartner][anim].mDirections[d][f].Models[name]`');
  p('   (fallback: keep the placeholder); then style sheet `mModels[name]`: skip if `mVisible` false; if `mGroup_Remap` →');
  p('   use `mGroups[styleSheet.mGroup_Remap][anim]...Models[name]` when present.');
  p('3. **PEdge**: `lineStyle(PEdge.mThickness=2, mColor 0, mAlpha 100)`; each polyline `[x0,y0,x1,y1,...]`: moveTo + lineTo...;');
  p('   then `beginFill(0,0); lineStyle(0,0,0); endFill()` (turns the stroke off). Drawn BEFORE the model\'s fills, so only');
  p('   the outer half of the 2 px line stays visible (outline).');
  p('4. **Shape_vList[i]** with `Shape_Material[i]` (key into the active material table) and `Shape_Matrix[i]`: matrix');
  p('   object → `beginBitmapFill(mat.sBMD, matrix, repeat=true, smooth=true)`; `0` → `beginFill(mat.mColor, mat.mAlpha)`;');
  p('   moveTo/lineTo over the flat list; `endFill()`. Then if `Shape_Brightness[i]` is non-zero: same polygon filled');
  p('   white (b ≥ 0) or black (b < 0) with alpha `100·|b|·mShader_Contrast(0.5)` percent.');
  p('5. **Shadow** polygons → `mcShadow` with Shadow material (black, 100). `mcShadow.filters = [DropShadowFilter(0,0,0,1,4,4,0.25,1,');
  p('   false,false,hideObject=true)]` → only a soft 25% shadow remains, under `mcGraphic`.');
  p('6. `Edge` (always empty) and `mLight` are not used. `RenderToBitmap` then rasterizes `mcContainer` at `mGlobalScale`');
  p('   (`getBounds` → floor/ceil → ×scale → `inflate(2,2)` quirk) and applies `GlowFilter(0x000000,1,4,4,2,1)`.');
  p();
  p('Style sheets (`CDrawPrimitive_XSI_StyleSheet`): start from `GetStyleSheet("Player_Handgun_Walk")` (a copy of all');
  p('master materials + one `{mGroup_Remap: undefined, mVisible: true}` per model name), then hide `GunPosition_Right`,');
  p('`Body_Front`, `Body_Back` (and `Weapon_Right` for zombie/devil), set `mGroup_Remap` (SS_SWAT/SS_GIJOE →');
  p('`Player_Alternate1` for Head/Foot_Right/Foot_Left; SS_ZOMBIE → `Zombie` Head; SS_DEVIL → `Devil` Head), swap the 7');
  p('bitmap materials\' `mcLinkID` to `<Skin>_Body_*`/`<Skin>_Head_*` and recolour solid materials.');
  p('`CDrawPrimitive_XSI_Collection` maps game animation names (stand, walk, shothit_1, ...) to loaded animations;');
  p('`MimicItem` aliases (grenadewalk → walk, ...).');
  p();
  // remap / partner compatibility
  p('Partner / remap availability for the sets the game loads (`Load(link)` calls in `Thing/Creature/*.as`):');
  p();
  const loads: [string, string[], string[]][] = [
    ['Player', ['Player_Stand', 'Player_Walk', 'Player_HitRear', 'Player_HitFront', 'Player_Dying', 'Player_Dead',
      'Player_Handgun_Walk', 'Player_Handgun_Stand', 'Player_Shotgun_Walk', 'Player_Shotgun_Stand', 'Player_UZI_Walk',
      'Player_UZI_Stand', 'Player_Rocket_Walk', 'Player_Rocket_Stand', 'Player_Railgun_Walk', 'Player_Railgun_Stand'], ['Player_Alternate1']],
    ['Zombie', ['Zombie_Zombie_Stand', 'Zombie_Zombie_Walk', 'Zombie_Zombie_Attack', 'Player_HitRear', 'Player_HitFront',
      'Player_Dying', 'Player_Dead'], ['Zombie']],
    ['Devil', ['Player_Stand', 'Player_Walk', 'Player_HitRear', 'Player_HitFront', 'Player_Dying', 'Player_Dead',
      'Devil_Devil_Attack'], ['Devil']],
  ];
  p('| creature | link | dirs×frames | partner set | remap set(s) | FillXSIInfo anchors present (d0 f0) |');
  p('|---|---|---|---|---|---|');
  for (const [creature, links, remaps] of loads) {
    for (const link of links) {
      const v = byId.get(link);
      if (!v) { p(`| ${creature} | ${link} | **missing** | | | |`); continue; }
      const dims = (x: XsiItemView | undefined) => (x ? `${x.rotations.length}×${x.rotations[0].length}` : '—');
      const partner = v.renderPartner ? byId.get(`${v.renderPartner}_${v.animID}`) : undefined;
      const rem = remaps.map((g) => `${g}_${v.animID} ${dims(byId.get(`${g}_${v.animID}`))}`).join(', ');
      const M = frameModels(v.rotations[0][0]);
      const anchors = ['Hand_Right', 'Hand_Left', 'GunPosition_Right'].map((n) => {
        const m = asGet(M, n);
        return `${n}:${m === undefined ? 'absent' : isEmptyModel(m) ? 'Empty' : asGet(asGet(m, 'XSIInfo'), 'vPosition') ? 'yes' : 'no vPos'}`;
      }).join(' ');
      p(`| ${creature} | ${link} | ${dims(v)} | ${v.renderPartner ? `${v.renderPartner}_${v.animID} ${dims(partner)}` : '—'} | ${rem} | ${anchors} |`);
    }
  }
  p();
  p('FillXSIInfo reads `Models[name].XSIInfo` of the LOADED set\'s frame (no partner substitution): where the anchor model is');
  p('`Empty`/absent, `XSIInfo` is undefined and the AS2 code produces NaN positions — port with `?.` and keep the NaNs.');
  p();

  // ------------------------------------------------------------------ ranges
  p('## 8. Value ranges and polygon facts');
  p();
  const vx = new Range(), vy = new Range(), sx = new Range(), sy = new Range(), ex = new Range(), bri = new Range();
  const mxr: Record<string, Range> = { a: new Range(), b: new Range(), c: new Range(), d: new Range(), tx: new Range(), ty: new Range() };
  const vpr: Record<string, Range> = { mX: new Range(), mY: new Range(), mZ: new Range() };
  const nVerts = new Map<number, number>();
  let zeroBright = 0, degenerate = 0, closing = 0, cw = 0, ccw = 0, nonInt = 0, negZero = 0, lenMismatch = 0, oddLen = 0;
  let texMismatch = 0, texPolys = 0, shadowPolys = 0, pedgeLines = 0, pedgePts = 0;
  const isTex = (name: string) => asGet([...matDefs.get(name)?.keys() ?? []].map((s) => JSON.parse(s) as AsValue)[0], 'mcLinkID') !== undefined;
  const numCheck = (v: number) => { if (!Number.isInteger(v)) nonInt++; if (Object.is(v, -0)) negZero++; };
  for (const v of views) for (const d of v.rotations) for (const f of d) for (const [, m] of frameModels(f).$) {
    if (isEmptyModel(m)) continue;
    const vl = asArray(asGet(m, 'Shape_vList'));
    const mt = asArray(asGet(m, 'Shape_Material'));
    const mx = asArray(asGet(m, 'Shape_Matrix'));
    const br = nums(asGet(m, 'Shape_Brightness'));
    if (mt.length !== vl.length || mx.length !== vl.length || br.length !== vl.length) lenMismatch++;
    vl.forEach((poly, i) => {
      const a = nums(poly);
      if (a.length % 2) oddLen++;
      inc(nVerts, a.length / 2);
      let area = 0;
      for (let k = 0; k < a.length; k += 2) {
        vx.add(a[k]); vy.add(a[k + 1]); numCheck(a[k]); numCheck(a[k + 1]);
        const k2 = (k + 2) % a.length;
        area += a[k] * a[k2 + 1] - a[k2] * a[k + 1];
      }
      if (a.length >= 4 && a[0] === a[a.length - 2] && a[1] === a[a.length - 1]) closing++;
      if (Math.abs(area) < 1e-9) degenerate++; else if (area < 0) ccw++; else cw++;
      const tex = isTex(String(mt[i]));
      if (tex) texPolys++;
      if (tex !== isAsObject(mx[i])) texMismatch++;
      if (isAsObject(mx[i])) for (const k of Object.keys(mxr)) mxr[k].add(asGet(mx[i], k) as number);
      else if (mx[i] !== 0) texMismatch++;
    });
    for (const b of br) { bri.add(b); if (b === 0) zeroBright++; }
    for (const poly of asArray(asGet(m, 'Shadow'))) { shadowPolys++; const a = nums(poly); for (let k = 0; k < a.length; k += 2) { sx.add(a[k]); sy.add(a[k + 1]); } }
    for (const poly of asArray(asGet(m, 'PEdge'))) { pedgeLines++; const a = nums(poly); pedgePts += a.length / 2; for (let k = 0; k < a.length; k += 2) ex.add(a[k]); }
    if (asArray(asGet(m, 'Edge')).length) lenMismatch++;
    const vp = asGet(asGet(m, 'XSIInfo'), 'vPosition');
    for (const k of Object.keys(vpr)) vpr[k].add(asGet(vp, k) as number);
  }
  p('| quantity | range |');
  p('|---|---|');
  p(`| Shape_vList x | ${vx} |`);
  p(`| Shape_vList y | ${vy} |`);
  p(`| Shadow x / y | ${sx} / ${sy} |`);
  p(`| PEdge x | ${ex} |`);
  p(`| Shape_Brightness | ${bri}; zero (no overlay): ${zeroBright} |`);
  for (const k of Object.keys(mxr)) p(`| Shape_Matrix.${k} | ${mxr[k]} |`);
  for (const k of Object.keys(vpr)) p(`| XSIInfo.vPosition.${k} | ${vpr[k]} |`);
  p();
  p(`- Polygon vertex counts: ${[...nVerts].sort((a, b) => a[0] - b[0]).map(([k, n]) => `${k}: ${n}`).join(', ')}.`);
  p(`- Coordinates are integers in XSI units (non-integer values: ${nonInt}; negative zeros: ${negZero}); the renderer scales`);
  p('  them by `mGlobalScale` (0.35 / 0.44) when rasterizing. Origin = the character\'s ground point.');
  p(`- Winding as seen on screen (y down): ${cw} clockwise, ${ccw} counter-clockwise, ${degenerate} zero-area (edge-on faces). ${closing} polygons`);
  p('  repeat their first vertex at the end. Flash fills close polygons implicitly (no lineTo back to the start).');
  p(`- Parallel arrays Shape_vList/Shape_Material/Shape_Matrix/Shape_Brightness have equal lengths in every model`);
  p(`  (mismatches: ${lenMismatch}); odd-length coordinate lists: ${oddLen}; \`Edge\` is always \`[]\`.`);
  p(`- \`Shape_Matrix[i]\` is an object exactly when the material is a bitmap material (${texPolys} polygons; mismatches:`);
  p(`  ${texMismatch}), otherwise the number 0. Matrices map the 64×64 material bitmap into vList space.`);
  p(`- Shadow: ${shadowPolys} polygons; PEdge: ${pedgeLines} polylines with ${pedgePts} points.`);
  p();
  p('## 9. Unusual things');
  p();
  p('- The item key is spelled `mFrameSquence` (sic) in the data and in `CDrawPrimitive_XSI_DI`.');
  p('- `Player_Zombie_Walk` has 8 frames per direction with an 8-entry sequence that only uses frames 0..4 (§3).');
  p('- Head-only groups (`Player_Alternate1`, `Devil`, `Zombie`) and weapon groups keep `{Empty: true}` placeholders for the');
  p('  other parts **in depth order**, so substituting the partner\'s model at the placeholder slot keeps correct layering.');
  p('- Matrices are plain objects `{a,b,c,d,tx,ty}` handed to `beginBitmapFill` (Flash reads the fields by name).');
  p('- `mLight` and `Edge` are dead data; lighting is baked into `Shape_Brightness`.');
  p('- The DoAction is plain straight-line code: no obfuscation (unlike the class code), no branches, no functions.');
  p();
  return L.join('\n');
}

